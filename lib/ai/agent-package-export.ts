/* ============================================
   PHASE 4 — AGENTS.md
   ============================================ */

export function renderAgentsMd(
  projectId: string,
  agentPackageDocumentId: string,
  pkg: AgentPackageDocument,
): string {
  const c = pkg.agent_contract;
  const out: string[] = [];
  out.push(FILE_MARK);
  out.push(`# AGENTS.md — ${pkg.title}\n\n`);
  out.push(
    "This file is the primary entry point for a coding agent. It was rendered deterministically from an approved VibePlan Agent Package. Do not reinterpret or regenerate it.\n\n",
  );

  out.push(
    section(
      "Project",
      table(
        ["Field", "Value"],
        [
          ["Project ID", projectId],
          ["Project name", pkg.project_context.project_name],
          ["Summary", pkg.project_context.project_summary],
          ["Objective", c.objective],
          ["Target users", pkg.project_context.target_users.join(", ")],
          ["Primary goals", pkg.project_context.primary_goals.join(", ")],
        ],
      ),
    ),
  );

  const sot = pkg.source_of_truth;
  out.push(
    section(
      "Source of Truth",
      "The following approved VibePlan artifacts are authoritative. If any implementation detail conflicts with them, the approved artifact wins.\n\n" +
        table(
          ["Artifact", "Document ID"],
          [
            ["Requirements", sot.requirements_document_id],
            ["Architecture", sot.architecture_document_id],
            ["ERD", sot.erd_document_id],
            ["DFD", sot.dfd_document_id],
            ["Flowchart", sot.flowchart_document_id],
            ["Implementation Blueprint", sot.blueprint_document_id],
            ["Agent Package", agentPackageDocumentId],
          ],
        ),
    ),
  );

  out.push(
    section(
      "Agent Contract",
      `### Objective\n\n${c.objective}\n\n` +
        `### MUST\n\n${bullets(c.must)}\n` +
        `### MUST NOT\n\n${bullets(c.must_not)}\n` +
        `### Allowed Changes\n\n${bullets(c.allowed_changes)}\n` +
        `### Prohibited Changes\n\n${bullets(c.prohibited_changes)}\n` +
        `### Required Checks\n\n${bullets(c.required_checks)}\n` +
        `### Escalation Rules\n\n${bullets(c.escalation_rules)}\n` +
        `### Completion Rules\n\n${bullets(c.completion_rules)}`,
    ),
  );

  out.push(
    section(
      "Project Rules",
      table(
        ["ID", "Category", "Rule"],
        pkg.project_rules.map((r) => [r.id, r.category, r.description]),
      ),
    ),
  );

  const strategy = pkg.implementation_strategy;
  out.push(
    section(
      "Implementation Strategy",
      "### Phases\n\n" +
        table(
          ["Phase ID", "Name", "Modules"],
          strategy.phases.map((p) => [p.id, p.name, p.modules.join(", ")]),
        ) +
        "\n### Dependency Order\n\n" +
        numbers(strategy.dependency_order),
    ),
  );

  out.push(
    section(
      "Uncertainty Protocol",
      "If implementation conflicts with an approved artifact:\n\n" +
        "```text\nSTOP.\nDo not guess.\nDo not silently modify the architecture.\nReport the conflict.\nRequest a human decision.\n```\n\n" +
        `### Triggers\n\n${bullets(pkg.uncertainty_protocol.triggers)}\n` +
        `### Required Actions\n\n${numbers(pkg.uncertainty_protocol.actions)}`,
    ),
  );

  out.push(
    section(
      "Forbidden Changes",
      table(
        ["Category", "Description"],
        pkg.forbidden_changes.map((f) => [f.category, f.description]),
      ),
    ),
  );

  out.push(
    section(
      "Definition of Done",
      pkg.definition_of_done
        .map((d) => `### ${d.category}\n\n${bullets(d.criteria)}`)
        .join("\n"),
    ),
  );

  out.push(
    section(
      "Assumptions",
      bullets(pkg.assumptions),
    ),
  );

  return out.join("").replace(/\n{3,}/g, "\n\n");
}

