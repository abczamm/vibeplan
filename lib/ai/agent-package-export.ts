/**
 * Deterministic, filesystem-safe slug.
 * Only [a-z0-9-]; never produces ".", "..", separators, or absolute paths.
 */
export function sanitizeFileSlug(raw: string): string {
  return raw
    .toLowerCase()
    .normalize("NFKD")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+/, "")
    .replace(/-+$/, "")
    .slice(0, 64)
    .replace(/-+$/, "");
}

function mdEscapeCell(value: string): string {
  return value.replace(/\|/g, "\\|").replace(/\r?\n/g, "<br>");
}

function bullets(items: string[]): string {
  if (items.length === 0) return "_None._\n";
  return items.map((i) => `- ${i}\n`).join("");
}

function numbers(items: string[]): string {
  if (items.length === 0) return "_None._\n";
  return items.map((i, idx) => `${idx + 1}. ${i}\n`).join("");
}

function table(headers: string[], rows: string[][]): string {
  if (rows.length === 0) return "_None._\n";
  const head = `| ${headers.map(mdEscapeCell).join(" | ")} |\n`;
  const sep = `| ${headers.map(() => "---").join(" | ")} |\n`;
  const body = rows
    .map((r) => `| ${r.map((c) => mdEscapeCell(String(c))).join(" | ")} |\n`)
    .join("");
  return head + sep + body + "\n";
}

function section(title: string, body: string): string {
  return `## ${title}\n\n${body}\n`;
}

