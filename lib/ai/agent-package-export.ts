/**
 * Deterministic module file name: sanitized slug + stable de-duplication.
 * Returns modules sorted by implementation_order mapped to their file paths.
 */
export function assignModuleFilePaths(modules: AgentModule[]): {
  module: AgentModule;
  path: string;
}[] {
  const sorted = [...modules].sort(
    (a, b) => a.implementation_order - b.implementation_order || (a.id < b.id ? -1 : 1),
  );
  const used = new Set<string>();
  const result: { module: AgentModule; path: string }[] = [];
  for (const m of sorted) {
    let slug = sanitizeFileSlug(m.name) || sanitizeFileSlug(m.code) || sanitizeFileSlug(m.id) || "module";
    if (!PATH_SEGMENT_SAFE.test(slug)) slug = "module";
    let candidate = slug;
    let counter = 2;
    while (used.has(candidate)) {
      candidate = `${slug}-${counter}`;
      counter++;
    }
    used.add(candidate);
    result.push({ module: m, path: `modules/${candidate}.md` });
  }
  return result;
}

