export function renderErdMd(e: ERDDocument): string {
  const out: string[] = [];
  out.push(FILE_MARK);
  out.push("# ERD (Approved)\n\n");
  out.push(
    `Rendered deterministically from the approved ERD (version ${e.version}, database: ${e.database}). Entity names and table names are authoritative identifiers.\n\n`,
  );
  out.push(section("Summary", `${e.summary}\n`));

  out.push(
    section(
      "Entities",
      e.entities
        .map((ent) => {
          const cols = table(
            ["Column", "Type", "Nullable", "PK", "Unique", "Default", "References", "Description"],
            ent.columns.map((c) => [
              c.name,
              c.type,
              c.nullable ? "yes" : "no",
              c.primary_key ? "yes" : "no",
              c.unique ? "yes" : "no",
              c.default_value ?? "",
              c.references ? `${c.references.entity}.${c.references.column}` : "",
              c.description,
            ]),
          );
          return `### ${ent.name} (\`${ent.table_name}\`)\n\n${ent.description}\n\n${cols}`;
        })
        .join("\n"),
    ),
  );

  out.push(
    section(
      "Relationships",
      table(
        ["ID", "From", "To", "Cardinality", "Foreign key", "Description"],
        e.relationships.map((rel) => [
          rel.id,
          rel.from_entity,
          rel.to_entity,
          rel.cardinality,
          rel.foreign_key ? `${rel.foreign_key.entity}.${rel.foreign_key.column}` : "",
          rel.description,
        ]),
      ),
    ),
  );

  out.push(
    section(
      "Indexes",
      table(
        ["Name", "Entity", "Columns", "Unique", "Reason"],
        e.indexes.map((i) => [
          i.name,
          i.entity,
          i.columns.join(", "),
          i.unique ? "yes" : "no",
          i.reason,
        ]),
      ),
    ),
  );

  out.push(
    section(
      "Constraints",
      table(
        ["ID", "Entity", "Type", "Description"],
        e.constraints.map((c) => [c.id, c.entity, c.type, c.description]),
      ),
    ),
  );

  out.push(
    section(
      "Assumptions",
      table(
        ["ID", "Description", "Reason"],
        e.assumptions.map((a) => [a.id, a.description, a.reason]),
      ),
    ),
  );

  return out.join("").replace(/\n{3,}/g, "\n\n");
}

