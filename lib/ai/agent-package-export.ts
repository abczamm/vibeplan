export function renderImplementationMd(pkg: AgentPackageDocument): string {
  const out: string[] = [];
  out.push(FILE_MARK);
  out.push(`# IMPLEMENTATION — ${pkg.title}\n\n`);
  out.push(
    "Actionable implementation guidance rendered from the approved Agent Package. This is guidance, not generated source code.\n\n",
  );

  const ordered = [...pkg.modules].sort(
    (a, b) => a.implementation_order - b.implementation_order || (a.id < b.id ? -1 : 1),
  );

  out.push(
    section(
      "Implementation Order",
      table(
        ["Order", "Module ID", "Name", "Dependencies"],
        ordered.map((m) => [
          String(m.implementation_order),
          m.id,
          m.name,
          m.dependencies.length ? m.dependencies.join(", ") : "—",
        ]),
      ),
    ),
  );

  out.push(
    section(
      "Phases & Dependency Order",
      "### Phases\n\n" +
        table(
          ["Phase ID", "Name", "Modules"],
          pkg.implementation_strategy.phases.map((p) => [
            p.id,
            p.name,
            p.modules.join(", "),
          ]),
        ) +
        "\n### Dependency Order\n\n" +
        numbers(pkg.implementation_strategy.dependency_order),
    ),
  );

  out.push(
    section(
      "Database Setup",
      "Follow the approved ERD and Blueprint. Do not silently change schema.\n\n" +
        table(
          ["Table", "Source entity", "PK", "Timestamps", "RLS"],
          pkg.database_instructions.map((d) => [
            d.table_name,
            d.source_entity_id,
            d.primary_key,
            d.timestamps_required ? "required" : "not required",
            d.rls_requirements.length ? `${d.rls_requirements.length} rule(s)` : "—",
          ]),
        ) +
        "\nSee `database/database-plan.md` for full column, constraint, index, audit, and seed requirements.",
    ),
  );

  out.push(
    section(
      "Authentication",
      table(
        ["Component", "Instruction"],
        pkg.authentication_instructions.map((a) => [a.component, a.instruction]),
      ),
    ),
  );

  out.push(
    section(
      "Authorization (RBAC)",
      table(
        ["Role / Permission", "Instruction"],
        pkg.authorization_instructions.map((a) => [
          a.role_or_permission,
          a.instruction,
        ]),
      ),
    ),
  );

  const backendRows: string[][] = [];
  for (const b of pkg.backend_instructions) {
    for (const instruction of b.instructions) backendRows.push([b.module_id, instruction]);
  }
  out.push(section("Backend", table(["Module", "Instruction"], backendRows)));

  out.push(
    section(
      "API",
      "See `api/api-contracts.md` for the full contract list. Contract summary:\n\n" +
        table(
          ["ID", "Method", "Route", "Module", "Auth"],
          pkg.api_contracts.map((a) => [
            a.id,
            a.method,
            a.route,
            a.module_id,
            a.authentication_required ? "required" : "public",
          ]),
        ),
    ),
  );

  const frontendRows: string[][] = [];
  for (const f of pkg.frontend_instructions) {
    for (const instruction of f.instructions) frontendRows.push([f.module_id, instruction]);
  }
  out.push(section("Frontend", table(["Module", "Instruction"], frontendRows)));

  out.push(
    section(
      "Validation",
      table(
        ["Target", "Instruction"],
        pkg.validation_instructions.map((v) => [v.target, v.instruction]),
      ),
    ),
  );

  out.push(
    section(
      "Security",
      table(
        ["Category", "Instruction"],
        pkg.security_instructions.map((s) => [s.category, s.instruction]),
      ) +
        "\nPer-module security requirements:\n\n" +
        table(
          ["Module", "Requirement"],
          pkg.modules.flatMap((m) =>
            m.security_requirements.map((r) => [m.id, r]),
          ),
        ),
    ),
  );

  out.push(
    section(
      "Testing",
      table(
        ["Module", "Category", "Instruction"],
        pkg.testing_instructions.map((t) => [t.module_id, t.category, t.instruction]),
      ),
    ),
  );

  out.push(
    section(
      "Completion Checks",
      "All of the following must hold before a task is considered done:\n\n" +
        pkg.definition_of_done
          .map((d) => `### ${d.category}\n\n${bullets(d.criteria)}`)
          .join("\n") +
        "\nRequired checks from the contract:\n\n" +
        bullets(pkg.agent_contract.required_checks),
    ),
  );

  return out.join("").replace(/\n{3,}/g, "\n\n");
}

